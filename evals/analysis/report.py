"""Eval report (ADR 0025): score by category and cost vs score per model.

Reads the latest evals/results/<model>-<date>.json of each model and writes, next to this file,
score-by-category.png, cost-vs-score.png and report.md.

    python evals/analysis/report.py
"""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

HERE = Path(__file__).parent
RESULTS = HERE.parent / "results"
CATEGORIES = ["simple", "several", "portions", "drinks", "typos", "ambiguous", "out-of-scope", "injection"]
COLORS = ["#2563B8", "#E08A4F", "#7FB2F0", "#9E2F22"]


def latest_runs() -> list[dict]:
    runs: dict[str, dict] = {}
    for file in sorted(RESULTS.glob("*.json")):
        run = json.loads(file.read_text(encoding="utf8"))
        if run.get("cases", 0) < 100:
            continue  # smoke tests
        runs[run["model"]] = run  # sorted by name: the last date wins
    return list(runs.values())


def main() -> None:
    runs = latest_runs()
    if not runs:
        raise SystemExit("no full runs in evals/results")
    by_category = pd.DataFrame(
        {r["model"]: [r["byCategory"].get(c, 0) for c in CATEGORIES] for r in runs}, index=CATEGORIES
    )
    summary = pd.DataFrame(
        [
            {
                "model": r["model"],
                "score": r["score"],
                "usd_150": r["costUsd"],
                "usd_per_entry": r["usdPerEntry"],
                "p50_s": r["latencyP50Ms"] / 1000,
                "p95_s": r["latencyP95Ms"] / 1000,
                "errors": r["errors"],
            }
            for r in runs
        ]
    ).sort_values("score", ascending=False)

    ax = by_category.plot.bar(figsize=(10, 4.5), color=COLORS[: len(runs)], width=0.8)
    ax.set_ylabel("score (0–100)")
    ax.set_ylim(0, 105)
    ax.set_title("Text logging agent: score by category")
    ax.legend(loc="lower left", fontsize=8)
    plt.xticks(rotation=20)
    plt.tight_layout()
    plt.savefig(HERE / "score-by-category.png", dpi=120)
    plt.close()

    fig, ax = plt.subplots(figsize=(6, 4.5))
    for i, row in enumerate(summary.itertuples()):
        ax.scatter(row.usd_per_entry * 1000, row.score, s=90, color=COLORS[i % len(COLORS)])
        ax.annotate(row.model, (row.usd_per_entry * 1000, row.score), textcoords="offset points", xytext=(6, 6), fontsize=8)
    ax.set_xlabel("USD per 1,000 proposed entries")
    ax.set_ylabel("score (0–100)")
    ax.set_title("Cost vs score")
    ax.grid(alpha=0.3)
    plt.tight_layout()
    plt.savefig(HERE / "cost-vs-score.png", dpi=120)
    plt.close()

    lines = [
        "# Eval report",
        "",
        "Generated by `python evals/analysis/report.py` from the latest full run of each model (150 synthetic phrases).",
        "",
        "| Model | Score | USD for 150 | USD per entry | p50 | p95 | Errors |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in summary.itertuples():
        lines.append(
            f"| {row.model} | {row.score:.1f} | {row.usd_150:.4f} | {row.usd_per_entry:.6f} | {row.p50_s:.1f} s | {row.p95_s:.1f} s | {row.errors} |"
        )
    lines += ["", "## Score by category", "", "| Category | " + " | ".join(by_category.columns) + " |", "| --- |" + " --- |" * len(by_category.columns)]
    for category, values in by_category.iterrows():
        lines.append(f"| {category} | " + " | ".join(f"{v:.1f}" for v in values) + " |")
    lines += ["", "![Score by category](score-by-category.png)", "", "![Cost vs score](cost-vs-score.png)", ""]
    (HERE / "report.md").write_text("\n".join(lines), encoding="utf8")
    print(summary.to_string(index=False))


if __name__ == "__main__":
    main()
