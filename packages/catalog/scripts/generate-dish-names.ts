/**
 * Step 1 of ADR 0028 layer 2: the dish list by category, with aliases, deduplicated against the curated and INS
 * dishes and between categories → seed/generated/dish-names.json. Run: node scripts/generate-dish-names.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { CATEGORIES } from '../src/generated/categories.ts';
import { dedupeNames, DishNames, type DishName } from '../src/generated/recipe.ts';
import { askJson } from './lib/ai.ts';

const root = new URL('../', import.meta.url);
const catalog = JSON.parse(readFileSync(new URL('dist/catalog.json', root), 'utf8')) as {
  dishes: { name: string }[];
};
const existing = catalog.dishes.map((d) => d.name);

const SYSTEM = `Eres un cocinero peruano que arma la lista de platos de una app de registro de comidas en Perú.
Responde solo JSON: {"names":[{"name":"...","aliases":["..."]}]}.
- Nombres en español como los dice la gente en Perú, con tildes; sin marcas comerciales ni nombres de restaurantes
- Cada nombre es un plato o preparación concreta que alguien anotaría tras comerla ("Torta helada", "Tequeños de queso")
- aliases: otros nombres comunes del mismo plato (0 a 3), nunca otro plato
- No repitas platos de la lista "ya existen" ni variantes triviales de ellos`;

const all: (DishName & { category: string })[] = [];
for (const category of CATEGORIES) {
  const taken = [...existing, ...all.map((n) => n.name)];
  const user = `Categoría: ${category.prompt}.
Dame ${category.target} platos distintos, de los más comunes a los menos comunes.
Ya existen (no los repitas): ${taken.join('; ')}`;
  const parsed = DishNames.safeParse(await askJson(`names:${category.id}`, SYSTEM, user));
  if (!parsed.success) {
    process.stderr.write(`${category.id}: invalid answer, skipped\n`);
    continue;
  }
  const kept = dedupeNames(
    parsed.data.names.map((n) => ({ ...n, category: category.id })),
    [...existing, ...all.flatMap((n) => [n.name, ...n.aliases])],
  );
  all.push(...kept);
  process.stdout.write(`${category.id}: ${parsed.data.names.length} asked → ${kept.length} kept\n`);
}

writeFileSync(
  new URL('seed/generated/dish-names.json', root),
  `${JSON.stringify(
    {
      about:
        'Dish list for the estimated recipes (ADR 0028 layer 2). Generated by scripts/generate-dish-names.ts; deduplicated against the curated and INS dishes.',
      names: all,
    },
    null,
    1,
  )}\n`,
);
process.stdout.write(`${all.length} names → seed/generated/dish-names.json\n`);
