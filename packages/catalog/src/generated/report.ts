import type { Checked, DishName, Recipe } from './recipe.ts';

/** What happened to one name of the list. */
export interface Outcome {
  name: DishName & { category: string };
  category: string;
  recipe: Recipe | null;
  checked: Checked;
  retried: boolean;
}

/** USD per 1M tokens (in, out) used to estimate the spend, read 2026-11-03. */
export const PRICES: Record<string, [number, number]> = {
  gemini: [0.1, 0.4],
  deepseek: [0.3, 1.2],
};

const median = (values: number[]) => {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted.length ? sorted[Math.floor(sorted.length / 2)]! : 0;
};
const round = (n: number) => Math.round(n);

/** reports/generated-dishes.md: counts, ranges per category, retries, failures and the AI spend. */
export function renderGeneratedReport(
  outcomes: readonly Outcome[],
  accepted: number,
  otherDishes: number,
  usage: readonly { provider: string; in: number; out: number }[],
): string {
  const lines: string[] = [
    '# Generated dishes (ADR 0028 layer 2)',
    '',
    'Generated by `scripts/generate-recipes.ts`. The AI picks ingredients and grams; every nutrient comes from the',
    'table. A recipe ships only when it passes the automatic checks (ids exist, kcal per 100 g and per serving in the',
    "category's range, protein + fat + carbohydrate ≤ 100 g per 100 g, energy known for ≥ 90% of the grams).",
    '',
    `- Names: ${outcomes.length} · accepted: **${accepted}** · after one corrected retry: ${outcomes.filter((o) => o.retried && o.checked.ok).length} · left out: ${outcomes.filter((o) => !o.checked.ok).length}`,
    `- Dishes in the catalog with the curated and INS ones: **${accepted + otherDishes}**`,
    '',
    '## By category',
    '',
    '| Category | Accepted | Left out | kcal / serving (median) | kcal / 100 g (median) | Protein / Fat / Carbs per serving (median g) |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  const categories = [...new Set(outcomes.map((o) => o.category))];
  for (const category of categories) {
    const mine = outcomes.filter((o) => o.category === category);
    const ok = mine.filter((o) => o.checked.ok && o.checked.totals);
    const t = (pick: (o: Outcome) => number | null | undefined) =>
      round(median(ok.map((o) => pick(o) ?? 0)));
    lines.push(
      `| ${category} | ${ok.length} | ${mine.length - ok.length} | ${t((o) => o.checked.totals?.perServing.energyKcal)} | ${t((o) => o.checked.totals?.per100g.energyKcal)} | ${t((o) => o.checked.totals?.perServing.proteinG)} / ${t((o) => o.checked.totals?.perServing.fatG)} / ${t((o) => o.checked.totals?.perServing.carbsTotalG)} |`,
    );
  }
  const failed = outcomes.filter((o) => !o.checked.ok);
  lines.push('', '## Left out', '');
  if (failed.length === 0) lines.push('None.');
  for (const o of failed)
    lines.push(`- ${o.name.name} (${o.category}): ${o.checked.errors.join('; ')}`);

  lines.push(
    '',
    '## AI spend',
    '',
    '| Provider | Calls | Tokens in | Tokens out | Estimated USD |',
    '| --- | --- | --- | --- | --- |',
  );
  let total = 0;
  for (const provider of [...new Set(usage.map((u) => u.provider))]) {
    const rows = usage.filter((u) => u.provider === provider);
    const tokensIn = rows.reduce((s, u) => s + u.in, 0);
    const tokensOut = rows.reduce((s, u) => s + u.out, 0);
    const [pin, pout] = PRICES[provider] ?? [0, 0];
    const usd = (tokensIn * pin + tokensOut * pout) / 1e6;
    total += usd;
    lines.push(
      `| ${provider} | ${rows.length} | ${tokensIn.toLocaleString('en')} | ${tokensOut.toLocaleString('en')} | ${usd.toFixed(3)} |`,
    );
  }
  lines.push(
    '',
    `Total estimated: USD ${total.toFixed(3)} (list prices; the Gemini free tier may make it 0).`,
    '',
  );
  return lines.join('\n');
}
