import type { Catalog } from './build-catalog.ts';

const pct = (value: number) => `${Math.round(value * 100)}%`;
const kcal = (value: number | null | undefined) => (value == null ? '—' : value.toFixed(0));

function table(header: string[], rows: string[][]): string {
  if (rows.length === 0) return '_None._\n';
  const line = (cells: string[]) => `| ${cells.join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n') + '\n';
}

/** Human review of an import: what is missing, approximated, converted or out of range. */
export function renderReport(catalog: Catalog): string {
  const count = (predicate: (f: Catalog['foods'][number]) => boolean) =>
    catalog.foods.filter(predicate).length;
  const flagged = catalog.crossChecks.filter((c) => c.flagged);
  const incomplete = catalog.dishes.filter((d) => d.totals.coverage.energyKcal < 1);

  return [
    '# Catalog import report',
    '',
    `Generated by \`pnpm --filter @kawsay/catalog build\` from \`seed/\` and \`sources/\` (ADR 0014, 0015). Do not edit.`,
    '',
    '## Summary',
    '',
    table(
      ['What', 'Count'],
      [
        ['Foods', String(catalog.foods.length)],
        ['… from INS', String(count((f) => f.source.kind === 'INS'))],
        ['… from USDA', String(count((f) => f.source.kind === 'USDA'))],
        ['… from labels', String(count((f) => f.source.kind === 'label' && f.status === 'ok'))],
        ['… labels to read', String(count((f) => f.status === 'label-pending'))],
        ['… unmatched', String(count((f) => f.status === 'unmatched'))],
        ['… proxies', String(count((f) => f.status === 'proxy'))],
        ['Dishes', String(catalog.dishes.length)],
        ['… cross-checked with group S', String(catalog.crossChecks.length)],
        ['… outside ±20%', String(flagged.length)],
      ],
    ),
    '## Unmatched',
    '',
    table(
      ['Food', 'Reason'],
      catalog.foods.filter((f) => f.status === 'unmatched').map((f) => [f.id, f.notes.join('; ')]),
    ),
    '## Labels to read',
    '',
    table(
      ['Food', 'Name'],
      catalog.foods.filter((f) => f.status === 'label-pending').map((f) => [f.id, f.name]),
    ),
    '## Proxies',
    '',
    table(
      ['Food', 'Row used', 'Why'],
      catalog.foods
        .filter((f) => f.status === 'proxy')
        .map((f) => [
          f.id,
          `${f.source.kind} ${f.source.code} ${f.source.name}`,
          f.notes.join('; '),
        ]),
    ),
    '## Cooked from raw',
    '',
    table(
      ['Food', 'Raw row', 'Factor', 'Reference'],
      catalog.foods
        .filter((f) => f.cookedToRaw)
        .map((f) => [
          f.id,
          `${f.source.code} ${f.source.name}`,
          String(f.cookedToRaw?.factor),
          f.cookedToRaw?.ref ?? '',
        ]),
    ),
    '## Other notes',
    '',
    table(
      ['Food', 'Source', 'Note'],
      catalog.foods
        .filter((f) => f.status === 'ok' && f.notes.length > 0)
        .map((f) => [f.id, `${f.source.kind} ${f.source.code ?? ''}`, f.notes.join('; ')]),
    ),
    '## Group S cross-check',
    '',
    'kcal per 100 g of the seed recipe vs the median of the INS strata. Over ±20%: review the recipe.',
    '',
    table(
      ['Dish', 'Group S', 'Recipe', 'INS median', 'Gap', ''],
      catalog.crossChecks.map((c) => [
        c.dish,
        `${c.code} (${c.strata} strata)`,
        kcal(c.dishKcalPer100g),
        kcal(c.referenceKcalPer100g),
        `${c.gap >= 0 ? '+' : ''}${pct(c.gap)}`,
        c.flagged ? '⚠️' : '✓',
      ]),
    ),
    '## Dishes with incomplete energy',
    '',
    table(
      ['Dish', 'Energy coverage', 'Missing'],
      incomplete.map((d) => [
        d.id,
        pct(d.totals.coverage.energyKcal),
        d.totals.missingFoods.join(', '),
      ]),
    ),
  ].join('\n');
}
