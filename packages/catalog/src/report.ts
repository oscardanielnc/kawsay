import { TAGS, type Catalog, type Inputs } from './build-catalog.ts';

const pct = (value: number) => `${Math.round(value * 100)}%`;
const VERDICT: Record<Catalog['crossChecks'][number]['verdict'], string> = {
  'within-20': '✓ within ±20%',
  'inside-strata-range': '✓ inside strata range',
  'weak-reference': '· weak reference',
  outside: '⚠️ review',
  accepted: '✓ accepted',
};
const kcal = (value: number | null | undefined) => (value == null ? '—' : value.toFixed(0));

function table(header: string[], rows: string[][]): string {
  if (rows.length === 0) return '_None._\n';
  const line = (cells: string[]) => `| ${cells.join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n') + '\n';
}

/**
 * Human review of an import: what is missing, approximated, converted or out of range; the added-sugar estimates
 * to check against a label and the tagged foods (F22, F24).
 */
export function renderReport(catalog: Catalog, addedSugar: Inputs['addedSugar'] = {}): string {
  const nameOf = new Map(catalog.foods.map((f) => [f.id, f.name]));
  const doubtful = Object.entries(addedSugar).filter(([, v]) => v.doubtful);
  const count = (predicate: (f: Catalog['foods'][number]) => boolean) =>
    catalog.foods.filter(predicate).length;
  const checks = (verdict: string) => catalog.crossChecks.filter((c) => c.verdict === verdict);
  const incomplete = catalog.dishes.filter((d) => d.totals.coverage.energyKcal < 1);

  return [
    '# Catalog import report',
    '',
    `Generated by \`pnpm --filter @kawsay/catalog build\` from \`seed/\` and \`sources/\` (ADR 0014, 0015). Do not edit.`,
    '',
    '## Summary',
    '',
    table(
      ['What', 'Count'],
      [
        ['Foods', String(catalog.foods.length)],
        ['… from INS', String(count((f) => f.source.kind === 'INS'))],
        ['… from USDA', String(count((f) => f.source.kind === 'USDA'))],
        ['… from labels', String(count((f) => f.source.kind === 'label' && f.status === 'ok'))],
        ['… labels to read', String(count((f) => f.status === 'label-pending'))],
        ['… generic INS foods (ingredients only, F23)', String(count((f) => f.generic === true))],
        ['… unmatched', String(count((f) => f.status === 'unmatched'))],
        ['… proxies', String(count((f) => f.status === 'proxy'))],
        ['Dishes', String(catalog.dishes.length)],
        ['… cross-checked with group S', String(catalog.crossChecks.length)],
        [
          '… agree (±20% or inside the strata range)',
          String(checks('within-20').length + checks('inside-strata-range').length),
        ],
        ['… accepted on purpose', String(checks('accepted').length)],
        ['… weak reference (< 5 establishments)', String(checks('weak-reference').length)],
        ['… to review', String(checks('outside').length)],
      ],
    ),
    '## Unmatched',
    '',
    table(
      ['Food', 'Reason'],
      catalog.foods.filter((f) => f.status === 'unmatched').map((f) => [f.id, f.notes.join('; ')]),
    ),
    '## Labels to read',
    '',
    table(
      ['Food', 'Name'],
      catalog.foods.filter((f) => f.status === 'label-pending').map((f) => [f.id, f.name]),
    ),
    '## Proxies',
    '',
    table(
      ['Food', 'Row used', 'Why'],
      catalog.foods
        .filter((f) => f.status === 'proxy')
        .map((f) => [
          f.id,
          `${f.source.kind} ${f.source.code} ${f.source.name}`,
          f.notes.join('; '),
        ]),
    ),
    '## Cooked from raw',
    '',
    table(
      ['Food', 'Raw row', 'Factor', 'Reference'],
      catalog.foods
        .filter((f) => f.cookedToRaw)
        .map((f) => [
          f.id,
          `${f.source.code} ${f.source.name}`,
          String(f.cookedToRaw?.factor),
          f.cookedToRaw?.ref ?? '',
        ]),
    ),
    '## Other notes',
    '',
    table(
      ['Food', 'Source', 'Note'],
      catalog.foods
        .filter((f) => f.status === 'ok' && f.notes.length > 0)
        .map((f) => [f.id, `${f.source.kind} ${f.source.code ?? ''}`, f.notes.join('; ')]),
    ),
    '## Group S cross-check',
    '',
    'kcal per 100 g of the seed recipe vs the median of the INS strata. Establishments come from INEI ENCONUT 2013,',
    'the survey behind group S. A recipe is questioned only when the reference is strong (≥ 5 establishments) and the',
    'recipe falls outside both ±20% and the range of the strata.',
    '',
    table(
      ['Dish', 'Group S', 'Establishments', 'Recipe', 'INS median', 'Gap', 'Verdict'],
      catalog.crossChecks.map((c) => [
        c.dish,
        `${c.code} (${c.strata} strata)`,
        c.establishments === null ? 'not in ENCONUT' : String(c.establishments),
        kcal(c.dishKcalPer100g),
        kcal(c.referenceKcalPer100g),
        `${c.gap >= 0 ? '+' : ''}${pct(c.gap)}`,
        VERDICT[c.verdict],
      ]),
    ),
    '### Accepted on purpose',
    '',
    table(
      ['Dish', 'Why'],
      catalog.crossChecks
        .filter((c) => c.acceptedBecause)
        .map((c) => [c.dish, c.acceptedBecause ?? '']),
    ),
    '## Dishes with incomplete energy',
    '',
    table(
      ['Dish', 'Energy coverage', 'Missing'],
      incomplete.map((d) => [
        d.id,
        pct(d.totals.coverage.energyKcal),
        d.totals.missingFoods.join(', '),
      ]),
    ),
    '## Added sugar to check against a label',
    '',
    table(
      ['Food', 'Name', 'g / 100 g', 'Why'],
      doubtful.map(([id, v]) => [id, nameOf.get(id) ?? '', String(v.g), v.from ?? '']),
    ),
    ...TAGS.flatMap((tag) => {
      const foods = catalog.foods.filter((f) => f.tags.includes(tag));
      const dishes = catalog.dishes.filter((d) => d.tags.includes(tag));
      return [
        `## Tag \`${tag}\` (${foods.length} foods, ${dishes.length} dishes)`,
        '',
        `${foods.map((f) => f.name).join(' · ')}\n`,
        `Dishes: ${dishes.map((d) => d.name).join(' · ') || '—'}\n`,
      ];
    }),
  ].join('\n');
}
